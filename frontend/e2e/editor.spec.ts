test('экспорт и импорт .xmind через меню', async ({ page }) => {
  await newMap(page, { version: 1, sheets: [{ id: 's', title: 'Л', rootTopic: { id: 'r', title: 'Экспорт', children: [{ id: 'a', title: 'Ветка', markers: ['priority-1'] }] } }] })
  await page.getByRole('button', { name: 'Меню' }).click()
  await page.getByRole('menuitem', { name: 'Экспортировать как' }).hover()
  const dl = page.waitForEvent('download')
  await page.getByRole('menuitem', { name: 'XMind', exact: true }).click()
  const file = await (await dl).path()
  await page.getByRole('button', { name: 'Меню' }).click()
  await page.getByRole('menuitem', { name: 'Файл', exact: true }).hover()
  const chooser = page.waitForEvent('filechooser')
  await page.getByRole('menuitem', { name: 'Импорт файла' }).click()
  await (await chooser).setFiles({ name: 'копия.xmind', mimeType: 'application/zip', buffer: readFileSync(file!) })
  await expect(page.locator('.title-input')).toHaveValue('копия')
  await expect(topic(page, 'Ветка').locator('[data-marker="priority-1"]')).toBeVisible()
})

test('комментарии: метка на карте, ответ, «решено»', async ({ page }) => {
  const id = await newMap(page)
  await page.getByRole('button', { name: 'Комментарии', exact: true }).click()
  await page.getByTestId('comments-panel').getByRole('button', { name: 'Добавить комментарий' }).last().click()
  await topic(page, 'Центральная тема').click()
  await page.getByLabel('Текст комментария').fill('Первый')
  await page.getByLabel('Отправить').click()
  await expect(page.getByTestId('comment-pin')).toHaveText('1')
  await page.getByLabel('Текст комментария').fill('Ответ')
  await page.keyboard.press('ControlOrMeta+Enter')
  await expect(page.getByTestId('comment-pin')).toHaveText('2')
  await expect.poll(async () => (await docOf(page, id)).sheets[0].rootTopic.comments?.map((c: { text: string }) => c.text)).toEqual(['Первый', 'Ответ'])
  await page.getByRole('dialog', { name: 'Обсуждение' }).getByLabel('Решено').click()
  await expect(page.getByTestId('comment-pin')).toHaveCount(0)
  await expect(page.getByText('Нет подходящих комментариев')).toBeVisible()
})

test('презентация: слайды и шаги', async ({ page }) => {
  await newMap(page)
  await topic(page, 'Центральная тема').click()
  await page.keyboard.press('Tab'); await page.keyboard.type('Первая'); await page.keyboard.press('Enter')
  await page.keyboard.press('Enter'); await page.keyboard.type('Вторая'); await page.keyboard.press('Enter')
  await page.getByLabel('Презентация', { exact: true }).click()
  const stage = page.locator('.pitch-stage')
  await expect(stage).toContainText('Центральная тема')
  await page.keyboard.press('ArrowRight')
  await expect(stage).toHaveAttribute('data-slide', '2')
  await page.keyboard.press('ArrowRight')
  await expect(stage).toContainText('Первая')
  await expect(stage).not.toContainText('Вторая')
  await page.keyboard.press('ArrowRight')
  await expect(stage).toContainText('Вторая')
  await page.keyboard.press('ArrowRight')
  await expect(stage).toHaveAttribute('data-slide', '3')
  await page.getByLabel('Выйти из презентации').click()
  await expect(page.getByTestId('presentation')).toHaveCount(0)
})

test('задача: панель слева, карточка в теме, диаграмма Ганта', async ({ page }) => {
  const id = await newMap(page)
  await topic(page, 'Центральная тема').click()
  await page.getByLabel('Вставить', { exact: true }).click()
  await page.getByRole('menuitem', { name: 'Задача' }).click()
  const panel = page.getByTestId('task-panel')
  await expect(panel).toBeVisible()
  await panel.getByLabel('Начало').fill('2026-10-10')
  await panel.getByLabel('Длительность').fill('3')
  await panel.getByLabel('Прогресс').selectOption('50')
  await expect.poll(async () => (await docOf(page, id)).sheets[0].rootTopic.taskInfo).toMatchObject({ start: '2026-10-10', end: '2026-10-12', progress: 50 })
  await expect(page.locator('.topic-task')).toContainText('3 дня')
  await page.getByLabel('Гант', { exact: true }).click()
  const g = page.getByTestId('gantt')
  await expect(g.locator('.gt-row:not(.head)')).toHaveCount(1)
  await expect(g.locator('.gc-bar')).toHaveCount(1)
  await panel.getByRole('switch', { name: 'Показывать в теме' }).click()
  await expect(page.locator('.topic-task')).toHaveCount(0)
  await panel.getByRole('button', { name: 'Удалить' }).click()
  await expect(g.locator('.gc-bar')).toHaveCount(0)
  await expect(panel).toContainText('В этой теме нет задачи')
  await panel.getByRole('button', { name: 'Вставить' }).click()
  await expect(g.locator('.gt-row:not(.head)')).toHaveCount(1)
})
