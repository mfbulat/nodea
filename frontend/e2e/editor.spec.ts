test('перетаскивание меняет родителя', async ({ page }) => {
  const id = await newMap(page, { version: 1, sheets: [{ id: 's', title: 'Л', rootTopic: { id: 'r', title: 'Корень', children: [
    { id: 'a', title: 'Первая', children: [{ id: 'a1', title: 'Лист' }] }, { id: 'b', title: 'Вторая', children: [] }] } }] })
  const from = await topic(page, 'Лист').boundingBox()
  const to = await topic(page, 'Вторая').boundingBox()
  await page.mouse.move(from!.x + from!.width / 2, from!.y + from!.height / 2)
  await page.mouse.down()
  await page.mouse.move(to!.x + to!.width / 2, to!.y + to!.height / 2, { steps: 8 })
  await page.mouse.up()
  await expectTree(page, id, 'Корень[Первая,Вторая[Лист]]')
})

